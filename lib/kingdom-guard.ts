// حارس نطاق المملكة — طبقة حتمية (لا تعتمد على النموذج إطلاقاً) تُطبَّق على النص
// الذي يولّده الذكاء قبل عرضه لصاحبة المنصة، فتصحّح آلياً أي مسمّى كيان ملغى أو
// غير سعودي انزلق إليه النموذج بحكم شيوعه العربي/الدولي. المبدأ: لا يصل الخطأ
// إلى المستخدم حتى لو أفلت من قاعدة الموجّه.
//
// ⚠️ لا تُطبَّق هذه الطبقة أبداً على نص المستخدم الأصلي أو على المقتطفات المنقولة
// حرفياً (excerpt/evidence) — فتلك ملك المستخدم تُنقل كما هي؛ تُطبَّق حصراً على
// النصوص الإنشائية التي تكتبها المنصة نفسها (الشروح، التوصيات، الملخصات).

export type EntityCorrection = { from: string; to: string };

// الترتيب مهم: الأطول أولاً حتى لا يلتهم نمط أقصر جزءاً من مسمّى أطول.
const CORRECTIONS: { pattern: RegExp; to: string }[] = [
  // جهة المحامين — لا «نقابة» في المملكة، الجهة هي الهيئة السعودية للمحامين
  { pattern: /نقابة\s+المحامين/g, to: "الهيئة السعودية للمحامين" },
  { pattern: /نقابة\s+المحاماة/g, to: "الهيئة السعودية للمحامين" },
  { pattern: /نقابة\s+محامين/g, to: "الهيئة السعودية للمحامين" },
  { pattern: /اتحاد\s+المحامين/g, to: "الهيئة السعودية للمحامين" },
  { pattern: /رابطة\s+المحامين/g, to: "الهيئة السعودية للمحامين" },
  { pattern: /مجلس\s+المحامين/g, to: "الهيئة السعودية للمحامين" },
  // «النقابة» المعرّفة في سياق المنصة (تعليق قانوني سعودي) مرجعها الهيئة حصراً —
  // لكن مع استثناء نقابات المهن الأخرى حتى لا تتلف عبارة مثل «النقابة الطبية»
  { pattern: /النقابة(?!\s*(?:الطبية|العمالية|الهندسية|المهندسين|الأطباء|المعلمين|الصيادلة|الصحفيين|التمريض|الزراعية|البيطرية))/g, to: "الهيئة السعودية للمحامين" },
  // مسميات جهات مُحدّثة — الاسم القديم مُلغى
  { pattern: /مؤسسة\s+النقد\s+العربي\s+السعودي/g, to: "البنك المركزي السعودي" },
  { pattern: /مؤسسة\s+النقد/g, to: "البنك المركزي السعودي" },
  { pattern: /وزارة\s+العمل\s+والتنمية\s+الاجتماعية/g, to: "وزارة الموارد البشرية والتنمية الاجتماعية" },
  { pattern: /وزارة\s+التجارة\s+والاستثمار/g, to: "وزارة التجارة" },
];

// تصحيحات إملائية حتمية لزلّات النموذج المتكررة — النموذج يُنتج أحياناً خطأً
// إملائياً عرضياً حتى في كلمة شائعة. القاعدة الصارمة لهذه القائمة: لا تُدرَج إلا
// صيغة «ليست كلمة عربية صحيحة في أي سياق» (لا لفظاً مستقلاً ولا كلمة+ضمير)، حتى
// لا يقع تصحيح خاطئ. محميّة بحدود الكلمة العربية فلا تمسّ ما بداخل كلمة أكبر.
const AR = "[\\u0600-\\u06FF]";
function w(word: string): RegExp {
  return new RegExp(`(?<!${AR})${word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?!${AR})`, "g");
}
const SPELLING_FIXES: { pattern: RegExp; to: string }[] = [
  { pattern: w("قواعس"), to: "قواعد" },        // قواعد السلوك المهني — رُصدت مرتين
  { pattern: w("هاذا"), to: "هذا" },
  { pattern: w("هاذه"), to: "هذه" },
  { pattern: w("محاميى"), to: "محامي" },
  { pattern: w("القضيةه"), to: "القضية" },
  { pattern: w("التاديبيه"), to: "التأديبية" },
  { pattern: w("تاديبيه"), to: "تأديبية" },
  { pattern: w("مسؤليه"), to: "مسؤولية" },
  { pattern: w("مسئوليه"), to: "مسؤولية" },
  { pattern: w("مسؤلية"), to: "مسؤولية" },
  { pattern: w("المسؤوليه"), to: "المسؤولية" },
  { pattern: w("المهنى"), to: "المهني" },       // ياء بلا نقطتين — ليست كلمة
  { pattern: w("مهنى"), to: "مهني" },
];

// تصحيح النص المولّد وإرجاع ما صُحّح (للتتبع الداخلي عند الحاجة)
export function sanitizeKingdomEntities(text: string): { text: string; corrections: EntityCorrection[] } {
  if (!text) return { text, corrections: [] };
  let out = text;
  const corrections: EntityCorrection[] = [];
  for (const { pattern, to } of [...CORRECTIONS, ...SPELLING_FIXES]) {
    out = out.replace(pattern, (match) => {
      corrections.push({ from: match, to });
      return to;
    });
  }
  return { text: out, corrections };
}

// مختصر يُرجع النص المصحّح فقط — للاستخدام المباشر على الحقول الإنشائية
export function sanitizeKingdom(text: string | undefined | null): string {
  if (!text) return text ?? "";
  return sanitizeKingdomEntities(text).text;
}
