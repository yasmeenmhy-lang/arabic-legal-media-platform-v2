//
// ما بقي هنا: تصنيف بصري تلقائي بحسب النطاق، بالقواعد العامة التي اعتمدتها
// المالكة نصاً — «ولا يستخدم هذا التصنيف لاتخاذ القرار، وإنما للعرض فقط».
// ─────────────────────────────────────────────────────────────────────────────

export type SourceCategory =
  | "حكومي"          // .gov.sa — جهة حكومية في المملكة العربية السعودية
  | "حكومي أجنبي"    // .gov وما جرى مجراه خارج المملكة
  | "منظمة دولية"    // .int
  | "منظمة"          // .org
  | "أكاديمي"        // .edu / .edu.sa / .ac.*
  | "موثّق";         // ما سواه — مصدر اجتازت صفتُه حكم الباحث

export function classifySourceUrl(url: string): SourceCategory {
  let host = "";
  try {
    host = new URL(url).hostname.toLowerCase().replace(/^www\./, "");
  } catch {
    host = (url || "").toLowerCase();
  }
  // حكومي المملكة العربية السعودية — النطاق .gov.sa لا تملكه إلا جهة حكومية فيها
  if (host.endsWith(".gov.sa") || host === "gov.sa") return "حكومي";
  // أكاديمي: نطاقات الجامعات والبحث العلمي
  if (host.endsWith(".edu") || host.endsWith(".edu.sa") || host.includes(".edu.") || host.includes(".ac.")) return "أكاديمي";
  // منظمة دولية رسمية: النطاق .int محجوز للمنظمات المنشأة بمعاهدات دولية
  if (host.endsWith(".int")) return "منظمة دولية";
  // حكومي أجنبي: .gov (الولايات المتحدة) ونظائره القُطرية مثل .gov.uk و.gouv.fr
  if (host.endsWith(".gov") || host.includes(".gov.") || host.includes(".gouv.")) return "حكومي أجنبي";
  // منظمة: .org
  if (host.endsWith(".org") || host.includes(".org.")) return "منظمة";
  return "موثّق";
}
