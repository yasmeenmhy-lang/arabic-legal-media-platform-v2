function findOfficialCorpusItem(ruleReference: string): OfficialCorpusItem | null {
  const ref = ruleReference.split(/[،\-–—]|الفقرة/)[0].trim();
  return OFFICIAL_CORPUS.find((item) => item.ref === ref) ?? null;
}

