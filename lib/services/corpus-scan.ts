// الطبقة الأولى — تحكم على النص بالقواعد واللائحة (بقرار مالكة المنصة)
//
// «الأولى تحكم على النص بالقواعد واللائحة، والثانية تتحقق وتراجع معنى النص
//  والنية فتُثبت الحكم أو تصححه».
//
// ★ تاريخ هذا الملف — لئلا يُعاد الخطأ:
// كان هنا كاشفٌ برمجي يبحث عن **قائمة عبارات مكتوبة باليد** («يعد جريمة»،
// «تسقط الدعوى»، «يعاقب» …) ولا يفتح المتن الرسمي إطلاقاً — بلا استيراد واحد
// منه. وكان مصرَّحاً في رأسه أنه «لا يُصدر حكماً»، فبقي الحكم كله للطبقة
// الثانية بلا مُحاسِب، فصدر على نصٍّ يمدح القضاء حكمٌ بمخالفة قاعدة تحمي
// القضاء من التشكيك.
//
// وقياسه على ثلاثة نصوص كشف أنه يخطئ في الاتجاهين معاً:
//   • إعلانٌ يضمن كسب الدعوى صراحةً — لم يلتقطه.
//   • سؤالٌ توعويٌّ بريء «متى تسقط الدعوى بالتقادم؟» — رفعه للفحص، لأن اللفظ
//     في قائمته، ولا يفرّق بين استفهامٍ وتقرير.
// فحُذفت القوائم المحفوظة، وصار الحكم قراءةً للمتن الرسمي نفسه.
//
// ★ لماذا قراءة لا مطابقة: لغة القواعد لا تشبه لغة الناس — «الوعد بتحقيق نتيجة»
// في القاعدة، و«تضمن لك أفضل نتيجة» في كلام المحامي. فالمطابقة الحرفية على
// المتن جُرّبت فلم تُصدر حكماً واحداً حتى على إعلانٍ يضمن النتيجة.
//
// ★ موضعها من الثانية: هذه تحكم **بالقاعدة** — تعرض النص على المتن بنداً بنداً؛
// والثانية تراجع **معنى النص والنية** فتُثبت أو تصحّح. والنهائي منها.
// ─────────────────────────────────────────────────────────────────────────────

import Anthropic from "@anthropic-ai/sdk";
import { recordUsage } from "@/lib/cost-meter";
import { buildOfficialRuleCorpusText } from "@/lib/rule-corpus-text";

export type FirstLayerVerdict = {
  ruleReference: string;   // القاعدة أو المادة كما وردت في المتن الرسمي
  clause: string;          // البند داخلها الذي وقعت المخالفة عليه
  evidence: string;        // المقطع من نصّ المحامي حرفاً — لا يُعاد صوغه
  reason: string;          // لِمَ خالف هذا المقطعُ هذا البندَ
};

const SYSTEM = `أنت الطبقة الأولى في محرّك امتثال لمنصة محتوى قانوني لمحامٍ مرخَّص في المملكة العربية السعودية.

## موضعك من المحرّك
أنت **تحكم على النص بالقواعد واللائحة**. وبعدك طبقة ثانية تراجع معنى النص والنية فتُثبت حكمك أو تصححه. فمهمتك أن تعرض النص على المتن الرسمي بنداً بنداً وتحكم بما فيه.

## المتن الرسمي الحاكم — كامل
${buildOfficialRuleCorpusText()}

## مهمتك
أنت قاضٍ لا مُتحفِّظ: اقرأ نصّ المحامي، ومُرَّ على كل قاعدة أو مادة يمسّها النص، **واحكم فيها صراحةً** — مخالفة أو لا. السكوت عن قاعدة مسّها النص ليس حكماً؛ الطبقة الثانية بعدك هي التي تتحقق من أحكامك، فلا تُوكل إليها حكمك.

## ضوابط الحكم
1. **الحكم بالمقصد**: القاعدة تُفهم بمقصدها، ونصّ المحامي يُفهم بمعناه — لا تشترط تطابق الحروف، ولا بنداً بلفظٍ صريح. جزمٌ قانوني بلا سند يخالف مقصدَ قاعدة الدقة في الظهور الإعلامي ولو لم يرد فيها لفظ «الجزم». واقرأ الجملة على وجهها: الاستفهام سؤالٌ لا تقرير، والثناء ثناءٌ لا تشكيك.
2. **تسمية السند**: مع كل مخالفة تُسمّي القاعدة أو المادة، والبند الأقرب إليها إن وُجد — فإن كانت المخالفة بمقصد القاعدة كلها فسمِّ القاعدة واذكر مقصدها في البند.
3. **الدليل الحرفي**: تنقل المقطع من نصّ المحامي **حرفاً بحرف** كما كتبه. ممنوع إعادة صوغه أو اختصاره.
4. **لا افتعال ولا إغفال**: النص الذي لا يخالف مقصد أي قاعدة تُخرج له مصفوفة فارغة — ولا تختلق مخالفة لنصٍّ سليم. والنص الذي يخالف تحكم عليه في كل موضع خالف — ولا تكتفي بموضع وتترك آخر.

## المخرج
JSON فقط — مصفوفة، كل عنصر:
{"ruleReference":"القاعدة/المادة كما وردت","clause":"البند","evidence":"المقطع الحرفي من نص المحامي","reason":"لِمَ خالف هذا المقطع هذا البند"}
ولا شيء خارج المصفوفة.`;

// تُرجع null عند تعذّر الطبقة — وتعذّرها لا يُسقط المراجعة، تمضي الثانية كما كانت.
export async function judgeByRules(text: string, timeoutMs = 90_000): Promise<FirstLayerVerdict[] | null> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) return null;
  try {
    const client = new Anthropic({ apiKey });
    const message = await client.messages.create(
      {
        model: "claude-sonnet-5",
        thinking: { type: "disabled" },
        max_tokens: 4096,
        // المتن الرسمي ثابت — يُخزَّن مؤقتاً لدى المزود فلا يُعاد ترميزه كل مرة
        system: [{ type: "text", text: SYSTEM, cache_control: { type: "ephemeral" } }],
        messages: [{ role: "user", content: `## نصّ المحامي\n«${text}»` }],
      },
      { timeout: timeoutMs }
    );
    recordUsage(message.usage, { stage: "الطبقة الأولى — الحكم بالقواعد واللائحة", model: "claude-sonnet-5" });

    const raw = message.content.map((b) => (b.type === "text" ? b.text : "")).join("");
    const start = raw.indexOf("[");
    const end = raw.lastIndexOf("]");
    if (start < 0 || end < 0) return [];
    const parsed = JSON.parse(raw.slice(start, end + 1)) as unknown;
    if (!Array.isArray(parsed)) return [];

    return parsed
      .filter((v): v is Record<string, unknown> => typeof v === "object" && v !== null)
      .map((v) => ({
        ruleReference: String(v.ruleReference ?? ""),
        clause: String(v.clause ?? ""),
        evidence: String(v.evidence ?? ""),
        reason: String(v.reason ?? ""),
      }))
      // الضابطان (١) و(٢) يُنفَّذان هنا لا يُوصى بهما: حكمٌ بلا مرجع أو بلا دليل يسقط
      .filter((v) => v.ruleReference.trim().length > 0 && v.evidence.trim().length > 0);
  } catch (error) {
    console.error("[layer1] failed:", error);
    return null;
  }
}
