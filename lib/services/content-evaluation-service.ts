const VALID_RISK_LEVELS: RiskLevel[] = ["منخفض", "متوسط", "مرتفع", "بالغ"];
const VALID_PARTIES: RiskAffectedParty[] = ["الموكل", "المحامي", "المهنة"];
const VALID_CATEGORIES: LanguageIssueCategory[] = ["spelling", "grammar", "style", "readability", "اتساق المصطلحات"];
const VALID_SEVERITIES: LanguageIssueSeverity[] = ["low", "medium", "high", "critical"];

function extractJson(raw: string): string | null {
  // handle ```json ... ``` or ``` ... ``` wrapping
  const codeBlock = raw.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (codeBlock) return codeBlock[1].trim();
  const obj = raw.match(/\{[\s\S]*\}/);
  return obj ? obj[0] : null;
}

function parseEvaluationResponse(raw: string): ContentEvaluation {
  const jsonMatch = extractJson(raw);
  if (!jsonMatch) throw new Error("[evaluation] failed to parse: no JSON found in response");

  let parsed: Record<string, unknown>;
  try {
    parsed = JSON.parse(jsonMatch) as Record<string, unknown>;
  } catch {
    throw new Error("[evaluation] failed to parse: invalid JSON");
  }

  const rawRisks = parsed.risks as Record<string, unknown> ?? {};
  const rawWriting = parsed.professionalWriting as Record<string, unknown> ?? {};
  const rawLanguage = parsed.language as Record<string, unknown> ?? {};

  const affectedParties = (Array.isArray(rawRisks.affectedParties) ? rawRisks.affectedParties : [])
    .filter((p): p is RiskAffectedParty => VALID_PARTIES.includes(p as RiskAffectedParty));

  // اشتقاق المستوى حتمياً من عدد الجهات المتضررة — فلا يتناقض المستوى المعروض مع
  // الجهات الحمراء أبداً (خلل رصدته مالكة المنصة: «مرتفع» بجهتين فقط). القاعدة
  // الدستورية للمنصة: 0-1 جهة = منخفض، جهتان = متوسط، ثلاث = مرتفع، وتُصعَّد إلى
  // «بالغ» فقط حين يقرر النموذج تهديداً شاملاً للمنظومة مع تضرر الجهات الثلاث.
  const modelLevel = VALID_RISK_LEVELS.includes(rawRisks.level as RiskLevel)
    ? rawRisks.level as RiskLevel
    : "منخفض";
  // ★ تصعيد سمعة المهنة (بقرار مالكة المنصة): الإضرار بسمعة المهنة لا يُساوَم عليه —
  // المحامي يمثّل المهنة، فأيّ تضرّر لجهة «المهنة» يُصعَّد حتماً إلى «مرتفع» (حاجب)
  // ولو كانت الجهة الوحيدة المتضررة. تشديدٌ للكشف لا إضعاف له.
  const professionHarmed = affectedParties.includes("المهنة");
  const riskLevel: RiskLevel =
    affectedParties.length >= 3 ? (modelLevel === "بالغ" ? "بالغ" : "مرتفع")
    : professionHarmed ? "مرتفع"
    : affectedParties.length === 2 ? "متوسط"
    : "منخفض";

  // حارس نطاق المملكة الحتمي على النصوص الإنشائية فقط (لا يمس excerpt المنقول حرفياً)
  const risks: ContentEvaluationRisks = {
    level: riskLevel,
    affectedParties,
    explanation: String(rawRisks.explanation ?? ""),
    fix: String(rawRisks.fix ?? "")
  };

  // ★ استثناء الولاية — حتمي في الكود لا في التوجيه: النموذج يُصنّف فقط (outOfMandate)،
  // والمنصة هي التي تتصرّف. الخطاب الديني والعقدي والفتوى خارج ما تغطّيه المنصة، فلا
  // يُقاس أسلوبه بمعيار الكتابة القانونية ولا يُطالَب بلغة المهنة — إذ لا معنى لأن تنتقد
  // المنصة نصّاً أعلنت أنها لا تغطّيه ثم ترفض إعانته. لا يمسّ هذا المخاطرَ ولا اللغةَ:
  // كلاهما مُقيَّم كاملاً، وكل مخالفة أو مساس بكرامة المهنة يُرصد كما يُرصد في أي نص.
  const outOfMandate = parsed.outOfMandate === true || rawWriting.outOfMandate === true;
  const profScore = Math.max(0, Math.min(100, Number(rawWriting.score) || 0));
  const professionalWriting: ContentEvaluationProfessionalWriting = outOfMandate
    ? { score: 85, passed: true, explanation: OUT_OF_MANDATE_NOTICE, fix: "" }
    : {
        score: profScore,
        passed: Boolean(rawWriting.passed ?? profScore >= PROFESSIONALISM_THRESHOLD),
        explanation: String(rawWriting.explanation ?? ""),
        fix: String(rawWriting.fix ?? "")
      };

  const langScore = Math.max(0, Math.min(100, Number(rawLanguage.score) || 0));
  const rawIssues = Array.isArray(rawLanguage.issues) ? rawLanguage.issues : [];
  // مرشّح حتمي للاعترافات الذاتية: ملاحظة يقول نصُّ وصفها نفسه إن الجملة سليمة
  // ولا خطأ فيها ليست ملاحظة أصلاً — رُصدت فعلياً من النموذج («لا يوجد خطأ نحوي في
  // هذا التركيب؛ الجملة سليمة») وهي تحجب التسليم بلا أي عيب حقيقي. الحذف هنا قطعي
  // بنص الملاحظة ذاتها، لا حكم ذكاء ولا تخفيف لأي رصد يصف خطأً فعلياً.
  const selfAdmittedNoError = /لا يوجد خطأ|الجملة سليمة|لا تستدعي تصحيح|لا يستدعي تصحيح/;
  const issues: ContentEvaluationLanguageIssue[] = rawIssues
    .filter((issue): issue is Record<string, unknown> => typeof issue === "object" && issue !== null)
    .map((issue) => ({
      category: VALID_CATEGORIES.includes(issue.category as LanguageIssueCategory)
        ? issue.category as LanguageIssueCategory
        : "readability",
      severity: VALID_SEVERITIES.includes(issue.severity as LanguageIssueSeverity)
        ? issue.severity as LanguageIssueSeverity
        : "medium",
      excerpt: String(issue.excerpt ?? ""), // منقول حرفياً من نص المستخدم — لا يُمس
      message: String(issue.message ?? issue.description ?? ""),
      suggestion: String(issue.suggestion ?? issue.fix ?? "")
    }))
    .filter((issue) => !selfAdmittedNoError.test(issue.message));

  const language: ContentEvaluationLanguage = {
    score: langScore,
    passed: Boolean(rawLanguage.passed ?? langScore >= LANGUAGE_THRESHOLD),
    issues
  };

  return { risks: enforceStyleOutOfRisks(risks), professionalWriting, language };
}

// ★★ إنفاذ ضابط فصل الأسلوب عن المخاطر (بقرار مالكة المنصة — رُصد الخرق حياً):
// الضابط منصوص عليه في الموجّه أعلاه بأدق صياغة، وحتى العبارة الممنوعة مذكورة
// حرفياً — ومع ذلك أخرج النموذج: «استخدام أسلوب عامي دارج في وصف انطباع عن جهة
// قضائية يُعرِّض كاتبه لمساءلة مهنية…». فالتوجيه وحده لا يُعوَّل عليه، والقاعدة
// تُنفَّذ على المخرج لا تُكتب فحسب.
//
// المعالجة: تُحذف من تعليل المخاطر كل جملة مبنية على الأسلوب أو اللغة أو النبرة.
// ولا يُمسّ مستوى الخطر ولا الجهات المتضررة هنا — فمستواهما محكوم بالمخالفات
// المرصودة وبالضرر الواقعي، وهما مساران مستقلان عن الأسلوب أصلاً. وإن لم يبقَ
// من التعليل شيء، وُضع تعليل صريح بأن ما رُصد أسلوبٌ محلُّه محورا اللغة والجوانب
// المهنية — لا تعليل مبتور ولا فراغ.
const STYLE_IN_RISKS = /(أسلوب|الأسلوب|عامي|عامية|العامية|دارج|دارجة|الركاكة|ركيك|النبرة|نبرة|الرصانة|السرد)/;

function enforceStyleOutOfRisks(risks: ContentEvaluationRisks): ContentEvaluationRisks {
  const explanation = String(risks.explanation ?? "");
  if (!explanation || !STYLE_IN_RISKS.test(explanation)) return risks;

  const kept = explanation
    .split(/(?<=[.؟!])\s+/)
    .filter((sentence) => sentence.trim() && !STYLE_IN_RISKS.test(sentence))
    .join(" ")
    .trim();

  console.warn("[evaluation] خرق ضابط فصل الأسلوب عن المخاطر — حُذفت جمل الأسلوب من تعليل المخاطر");

  return {
    ...risks,
    explanation:
      kept ||
      "ما رُصد على هذا النص ملاحظات أسلوب ولغة، ومحلُّها محورا اللغة والجوانب المهنية — لا محور المخاطر.",
  };
}

function buildFallbackEvaluation(): ContentEvaluation {
  return {
    risks: { level: "منخفض", affectedParties: [], explanation: "تعذّر تقييم المخاطر.", fix: "" },
    professionalWriting: { score: 70, passed: true, explanation: "تعذّر التحقق من الرصانة المهنية.", fix: "" },
    language: { score: 70, passed: true, issues: [] }
  };
}

// سطر السياق يسبق النص في رسالة المستخدم (لا في الموجّه الثابت حفاظاً على التخزين
// المؤقت) — بقاعدة مالكة المنصة المؤسِّسة: كل نوع محتوى له خصائصه ومقاييسه،
// فالحكم على الأسلوب والرصانة يكون بمعيار النوع وقناته لا بمعيار واحد للجميع.
// ★ إعلان غياب الإطار صراحةً (بقرار مالكة المنصة): نصّ مسار المراجعة — وإعادة
// صياغته — يصل بلا نوع محتوى، فوجهة النشر مجهولة. كان الغياب ضمنياً يُستنتج من
// خلوّ سطر السياق، فيتذبذب حكم الأسلوب بين المطلق والمشروط. صار يُبلَّغ نصاً.
const NO_FRAMEWORK_LINE =
  "سياق النص — ★ لا إطار محتوى لهذا النص (مسار المراجعة): لم يُحدَّد نوع المحتوى ولا القناة ولا الجمهور ولا الهدف، فوجهة النشر **مجهولة**. وعليه تلزمك الصيغة المشروطة في ملاحظة الأسلوب العامي كما نُصّ عليه في محور اللغة، ويمتنع الحكم المطلق على الأسلوب.\n";

function hasFramework(context?: ReviewContext): boolean {
  return Boolean(context?.contentType || context?.channel || context?.audience || context?.purpose);
}

// ★★ سطر الفهم المثبّت (بقرار مالكة المنصة): «الأسلوب العامي مقبول إذا كان نص
// يوميات أو تعليق أو رسالة — هو مو كاتب مقالة». فحدّ الأسلوب يُقاس بطبيعة النص
// الفعلية، وهي معلومة الآن من الفهم المثبّت — لا تُظنّ ولا تُفترض مقالاً.
function buildUnderstandingLine(context?: ReviewContext): string {
  const u = context?.understanding;
  if (!u) return "";
  const styleRule = u.formalRegisterRequired
    ? "وهذا النوع يقتضي لغة فصيحة رصينة، فتُرصد العامية فيه ملاحظةَ أسلوب مقرِّرة بحسبه."
    : "★ وهذا النوع **لا يقتضي** لغة فصيحة رصينة — فالعامية فيه **مقبولة ولا تُرصد ملاحظةً ولا تُنقص الدرجة ولا تُذكر في أي محور**. لا يُقاس بمعيار المقال ما ليس مقالاً.";
  return `الفهم المثبّت لهذا النص (محسوب قبل التقييم — اعتمده ولا تُكوّن فهماً مخالفاً): ${u.nature} ومقصد كاتبه «${u.purport}». ${u.summary} ${styleRule}\n★ ولا تحكم بخلاف هذا المقصد: الثناء ثناء لا تشكيك، والإخبار إخبار لا ترويج.\n`;
}

function buildContextLine(context?: ReviewContext): string {
  const understandingLine = buildUnderstandingLine(context);
  if (!context) return NO_FRAMEWORK_LINE;
  if (!hasFramework(context)) return understandingLine + NO_FRAMEWORK_LINE;
  const parts = [
    context.contentType ? `نوع المحتوى: ${context.contentType}` : "",
    context.channel ? `القناة: ${context.channel}` : "",
    context.audience ? `الجمهور: ${context.audience}` : "",
    context.purpose ? `الهدف: ${context.purpose}` : "",
    context.specialty ? `التخصص: ${context.specialty}` : "",
    context.source ? `مصدر الفكرة: ${context.source}` : "",
    context.topic ? `الموضوع المدخل: ${context.topic}` : "",
  ].filter(Boolean);
  const base = understandingLine + (parts.length > 0 ? `سياق النص — ${parts.join("، ")}\n` : "");
  // نتائج التحقّق الحيّ من المصادر الموثوقة — تُعتمد في تقدير المخاطر على دقّة
  // الإحالات: «مؤكَّد» لا يُبنى عليه خطر دقّة، و«غير مطابق» خلل دقّة، و«تعذّر
  // التحقّق» يُعامَل بمعايرة الإحالة (لا تصعيد مخاطر لمجرّد تعذّر التحقّق اللحظي).
  const verification = context.verificationBriefing
    ? `نتائج تحقّق حيّ من مصادر موثوقة لإحالات هذا النص (اعتمدها في الحكم على الدقّة):\n${context.verificationBriefing}\n`
    : "";
  return base + verification;
}

// المخالفات المثبتة تُصاغ قسماً يُلحق برسالة المستخدم — بمرجعها وخطورتها ودليلها،
// فيقيس المحرّك الأثر وهو يعلم ما رُصد، لا من فراغ. محلّه رسالة المستخدم لا كتلة
// system المخزّنة مؤقتاً، لأنه يتغيّر بتغيّر النص.
function buildComplianceSection(findings: ReviewFinding[] | undefined): string {
  const active = (findings ?? []).filter((f) => !f.resolved);
  if (active.length === 0) return "";
  const items = active
    .map(
      (f, i) =>
        `${i + 1}. ${f.legalReference} — ${f.sourceDocument} [خطورة: ${f.severity}]\n   الدليل من النص: «${f.evidence}»\n   وجه المخالفة: ${f.explanation || f.issue}`
    )
    .join("\n");
  return `\n\n## مخالفات رُصدت في هذا النص (حكم صادر ومثبت — لا يُراجَع ولا يُنقض)\n${items}`;
}

// ★ complianceFindings **إلزامي** لا اختياري — بقرار مالكة المنصة: «الامتثال
// عنصر أساسي في قياس المخاطر» مبدأٌ عام للمنصة كلها لا عادةٌ يتذكّرها المستدعي.
// كان اختيارياً فطُبِّق في مسار وسقط من مسارين. وإلزامه يجعل المترجم نفسه يرفض
// أي مسار — قائم أو يُضاف مستقبلاً — يقيس المخاطر بلا علم بالمخالفات، فيُمسك
// الخطأ قبل النشر لا بعده. تُمرَّر [] صراحةً حين لا امتثال يُفحص.
export async function evaluateContent(
  text: string,
  context: ReviewContext | undefined,
  complianceFindings: ReviewFinding[]
): Promise<ContentEvaluation> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    console.warn("[evaluation] ANTHROPIC_API_KEY missing — returning fallback evaluation");
    return buildFallbackEvaluation();
  }

  const complianceSection = buildComplianceSection(complianceFindings);
  console.log(
    "[evaluation] starting content evaluation (risks, professionalism, language) — compliance findings passed:",
    (complianceFindings ?? []).filter((f) => !f.resolved).length
  );

  const client = new Anthropic({ apiKey });
  const MAX_ATTEMPTS = 2;

  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      const message = await client.messages.create({
        // Sonnet لا haiku: محرّك المخاطر يكتب شرحاً حراً ويحدد الجهات — النموذج
        // الأقوى أدق في الحكم وأقل زلّات إملائية (جذر خطأ «قواعس» من haiku)
        // أعلى مستوى فهم بقرار مالكة المنصة: أقوى نموذج + تفكير تمهيدي قبل الحكم
        model: "claude-opus-5",
        // تنبيه من SDK المثبت: النماذج بعد Opus 4.6 (ومنها Sonnet 5) ترفض أي حرارة
        // غير 1.0 بخطأ 400 — لا يوجد خيار «حرارة صفر» على هذا النموذج، فلا تُضبط.
        thinking: { type: "adaptive" },
        max_tokens: 12000,
        system: [{ type: "text", text: buildEvaluationSystem(), cache_control: { type: "ephemeral" } }],
        messages: [{ role: "user", content: `${buildContextLine(context)}«${text}»${complianceSection}` }]
      });

      recordUsage(message.usage, { stage: "مقيّم اللغة والمخاطر", model: "claude-opus-5" }); // عدّاد التكلفة الداخلي — قياس صرف

      if (message.stop_reason === "max_tokens") {
        throw new Error("response truncated at max_tokens — JSON incomplete");
      }

      const rawText = message.content
        .filter((block) => block.type === "text")
        .map((block) => (block as { type: "text"; text: string }).text)
        .join("");

      const result = parseEvaluationResponse(rawText);
      console.log(
        "[evaluation] done: risk=%s, professionalism=%d, language=%d",
        result.risks.level,
        result.professionalWriting.score,
        result.language.score
      );
      return result;
    } catch (err) {
      console.warn(
        `[evaluation] attempt ${attempt}/${MAX_ATTEMPTS} failed`,
        err instanceof Error ? err.message : ""
      );
    }
  }

  console.warn("[evaluation] all attempts failed — returning fallback evaluation");
  return buildFallbackEvaluation();
}
