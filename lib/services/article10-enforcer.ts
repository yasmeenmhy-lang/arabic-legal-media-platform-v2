// المنفّذ البرمجي الحتمي للمادة (١٠) من وثيقة حوكمة المصادر — بقرار مالكة
// المنصة الملزم: «تُنفذ المادة (١٠) كقاعدة برمجية حتمية، ولا تقتصر على توجيه
// النموذج داخل المطالبة».
//
// عند غياب المصدر الرسمي، يفحص هذا الكود النص الناتج ويرصد التفاصيل النظامية
// المحظورة بنص المادة: رقم المادة أو القاعدة، والمدة أو المهلة أو الميعاد،
// والعقوبة، والأثر الإجرائي أو النظامي، والنسبة الرقمية.
//
// ★ الكاشف يرصد «الاستشهاد بتفصيلة نظامية»، لا «ذكر النظام»: تسمية نظامٍ في
// سياق الكلام ليست استشهاداً بنصّه (تصحيح رصدته مالكة المنصة بنفسها حين مُنع
// موضوع مشروع تماماً عن «آخر تشريعات في العقار»). والاستشهاد بقواعد السلوك
// المهني واللائحة التنفيذية مستثنى — متنهما مخزَّن في المنصة ولها متحقق حتمي
// مستقل (citation-verifier) يقارن الاستشهاد بالنص الحرفي.
//
// حتمي بلا ذكاء، كالطبقة الأولى. لا يمسّ مسار المراجعة: النص هناك نصّ المحامي،
// ومن حقّه أن يستشهد، والمنصّة تتحقّق وتُخبره ولا تمنعه.
// ─────────────────────────────────────────────────────────────────────────────

// سجل إنفاذ المادة (١٠) — يُخزَّن مع المهمة (بقرار مالكة المنصة، البند السابع
// من قرار الإنفاذ): توثيق كامل قابل للقياس بعد الإطلاق.
export type Article10Enforcement = {
  sourceFound: boolean;                       // هل وُجد مصدر رسمي مختص؟
  sources: { title: string; url: string }[];  // ما المصدر؟
  article10Applied: boolean;                  // هل طُبقت المادة (١٠)؟
  generalAllowed: boolean;                    // هل سُمح بالمحتوى العام؟
  stopped: boolean;                           // هل أوقف المحتوى؟
  violations: string[];                       // المخالفات المكتشفة
  correctionRounds: number;                   // عدد جولات التصحيح
  outcome: string;                            // النتيجة النهائية
};

// ★ الأنماط مكتوبة بالصيغة المطبَّعة (ا بلا همزة، ي مكان ى، ه/ة متسامحة) لأنها
// تُطابَق ضد نص مرّ بـnormalizeClaim — نمط بحرف غير مطبَّع لا يطابق أبداً
// (نفس علة \b القديمة التي عطّلت الطبقة الأولى يوماً).
const CLAIM_PATTERNS: Array<{ re: RegExp; label: string; requires?: RegExp }> = [
  { re: /(الماد[هة]|القاعد[هة])\s+(الاولي|الثاني|الثالث|الرابع|الخامس|السادس|السابع|الثامن|التاسع|العاشر|الحادي|\d|[٠-٩])/, label: "إحالة إلى مادة أو قاعدة برقمها" },
  { re: /(مدة|مهلة|ميعاد|خلال)(\s+\S+){0,2}\s+(\d+|[٠-٩]+|[يت]وما|شهرا|سنة|سنوات|ايام|ثلاثون|ثلاثين|ستون|ستين|تسعون|تسعين|مائة|اثني عشر)/, label: "مدة أو مهلة نظامية" },
  { re: /(يعاقب|تعاقب|عقوبته|عقوبتها|بالسجن|بالحبس|غرامة|يغرم)/, label: "عقوبة" },
  { re: /(تسقط الدعوي|يسقط الحق|عدم القبول شكلا|يبطل|بطلان|ينقضي الحق)/, label: "أثر إجرائي أو نظامي محدد" },
  // نسبة رقمية — المادة (١٠) تحظر «النسبة» عند غياب المصدر. النسبة الوصفية
  // العامة («نسبة كبيرة») ليست ادعاءً رقمياً فلا تُرصد.
  { re: /(\d+([.,]\d+)?|[٠-٩]+([.,][٠-٩]+)?)\s*[٪%]/, label: "نسبة رقمية" },
  // مدة صريحة (رقم + وحدة زمنية) دون لفظ «مدة» قبلها — كـ«يمنحك تسعين يوماً».
  // مشروطة بسياق نظامي في الجملة نفسها، فلا تُرصد «خبرة تتجاوز عشرين عاماً».
  {
    re: /(\d+|[٠-٩]+|ثلاثين|ثلاثون|ستين|ستون|تسعين|تسعون|مائة)\s+(يوما|يوم|شهرا|شهر|سنة|سنوات|اشهر)/,
    label: "مدة نظامية محددة",
    requires: /(نظام|ماد[هة]|لائح[هة]|دعوى|طعن|اعتراض|تقادم|مهل[هة]|ميعاد|يمنح|يجوز|يسقط|تسقط|يشترط|يلزم|الاختصاص)/,
  },
];

function normalizeClaim(text: string): string {
  return text
    .replace(/[ً-ْـ]/g, "")
    .replace(/[إأآا]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}

// أنظمة المتن المخزّن في المنصّة — مصدرها حاضر دائماً ولها متحققها المستقل
const IN_CORPUS = /نظام المحاما[هة]|اللائح[هة] التنفيذي[هة]|قواعد السلوك المهني/;

// يرصد التفاصيل النظامية المحظورة بالمادة (١٠) في نصٍّ بلا مصدر رسمي.
// sourceCount > 0 ⇒ المصدر حاضر والكاتب يكتب منه — لا رصد.
// الفحص على مستوى الجملة: الجملة المحيلة إلى متن المنصة مستثناة وحدها.
export function article10Violations(text: string, sourceCount: number): string[] {
  if (sourceCount > 0) return [];
  const hits: string[] = [];
  const seen = new Set<string>();
  for (const raw of text.split(/(?<=[.؟!])\s+|\n+/)) {
    const norm = normalizeClaim(raw);
    if (!norm.trim() || IN_CORPUS.test(norm)) continue;
    for (const { re, label, requires } of CLAIM_PATTERNS) {
      const match = norm.match(re);
      if (!match) continue;
      if (requires && !requires.test(norm)) continue;
      const entry = `${label}: «${match[0].trim().slice(0, 70)}»`;
      if (seen.has(entry)) continue;
      seen.add(entry);
      hits.push(entry);
    }
  }
  return hits;
}
