// المنفّذ البرمجي الحتمي للمادة (١٠) من وثيقة حوكمة المصادر — بقرار مالكة
// المنصة الملزم: «تُنفذ المادة (١٠) كقاعدة برمجية حتمية، ولا تقتصر على توجيه
// النموذج داخل المطالبة».
//
// التغطية: الفئات الثلاث عشرة المنصوص عليها في قرار الإنفاذ — لكل فئة كاشف
// برمجي مسمّى بها. الكاشف شبكة أمان حتمية خلف التوجيه الملزم في مطالبة الكاتب:
// التوجيه يحمل القاعدة العامة (الجذر)، والكاشف يمسك صورها المتحققة نصياً.
//
// ★ الأنماط مكتوبة بالصيغة المطبَّعة (ا بلا همزة، ي مكان ى، ه/ة متسامحة) لأنها
// تُطابَق ضد نص مرّ بـnormalizeClaim — نمط بحرف غير مطبَّع لا يطابق أبداً
// (نفس علة \b القديمة التي عطّلت الطبقة الأولى يوماً).
//
// ★ الكاشف يرصد «التفصيلة النظامية المؤكَّدة»، لا «ذكر النظام»: تسمية نظامٍ في
// سياق الكلام ليست ادعاءً بتفصيلة (تصحيح رصدته مالكة المنصة بنفسها). والاستشهاد
// بقواعد السلوك المهني واللائحة التنفيذية مستثنى — متنهما مخزَّن في المنصة وله
// متحقق حتمي مستقل (citation-verifier).
//
// حتمي بلا ذكاء، كالطبقة الأولى. لا يمسّ مسار المراجعة: النص هناك نصّ المحامي،
// ومن حقّه أن يستشهد، والمنصّة تتحقّق وتُخبره ولا تمنعه.
// ─────────────────────────────────────────────────────────────────────────────

// الإشارتان الحرفيتان اللتان يخرجهما الكاتب (لا تصلان المستخدم أبداً — تُلتقطان
// قبل أي فحص أو تسليم، ويشهد بذلك اختبار عدم التسرب)
export const ARTICLE10_STOP_MARKER = "[[إيقاف-المادة-10]]";
export const RESEARCH_NEEDED_MARKER = "[[بحاجة-بحث]]";

export type WriterMarker = "stop" | "research" | null;
export function detectWriterMarker(text: string): WriterMarker {
  const t = (text || "").trim();
  if (t.includes(ARTICLE10_STOP_MARKER)) return "stop";
  if (t.includes(RESEARCH_NEEDED_MARKER)) return "research";
  return null;
}

// سجل إنفاذ المادة (١٠) — يُخزَّن مع المهمة (بقرار مالكة المنصة، البند السابع
// من قرار الإنفاذ): توثيق كامل قابل للقياس بعد الإطلاق.
export type Article10Enforcement = {
  sourceFound: boolean;                       // هل وُجد مصدر رسمي مختص؟
  sources: { title: string; url: string }[];  // ما المصدر؟
  article10Applied: boolean;                  // هل طُبقت المادة (١٠)؟
  generalAllowed: boolean;                    // هل سُمح بالمحتوى العام؟
  stopped: boolean;                           // هل أوقف المحتوى؟
  violations: string[];                       // المخالفات المكتشفة
  correctionRounds: number;                   // عدد جولات التصحيح
  outcome: string;                            // النتيجة النهائية
};

// تعقيم سجل الإنفاذ قبل الحفظ الدائم (بقرار المالكة: لا نص محتوى في السجل) —
// تُحفظ تسمية الفئة وحدها دون المقتطف النصي.
export function sanitizeEnforcementForStorage(e: Article10Enforcement): Article10Enforcement {
  return {
    ...e,
    violations: e.violations.map((v) => v.split(":")[0].trim()),
  };
}

// ── كواشف الفئات الثلاث عشرة (بترقيم قرار الإنفاذ) ──
// شرط «requires»: قرينة سياق في الجملة نفسها تمنع الرصد الكاذب لكلام عام.
const REGULATORY_CONTEXT = /(نظام|النظام|نظاما|ماد[هة]|لائح[هة]|اللائح[هة]|قانون|القانون|تشريع|قرار وزاري|امر ملكي|مرسوم)/;
const GOV_BODY = /(وزار[هة]|الوزار[هة]|هيئ[هة]|الهيئ[هة]|محكم[هة]|المحكم[هة]|ديوان|الديوان|النياب[هة] العام[هة]|مجلس الوزراء|البنك المركزي|لجن[هة] فض|اللجن[هة] العليا|امار[هة]|بلدي[هة]|الجهات الحكومي[هة]|جه[هة] حكومي[هة])/;

const CLAIM_PATTERNS: Array<{ category: string; re: RegExp; requires?: RegExp }> = [
  // (١) الحكم النظامي — إسناد حكم قطعي إلى نظام أو قانون
  { category: "حكم نظامي", re: /(يجيز|يحظر|يمنع|يوجب|يمنح|يقرر|يعتبر|يقضي|اجاز|حظر|اوجب)\s+(النظام|القانون|نظام\s+\S+|قانون\s+\S+)/ },
  { category: "حكم نظامي", re: /(النظام|القانون)\s+(يجيز|يحظر|يمنع|يوجب|يمنح|يقرر|يعتبر|يقضي)/ },
  // (٢) التفسير النظامي — تحديد المقصود من نص نظامي («بـ» تلتصق بالكلمة بعدها)
  { category: "تفسير نظامي", re: /(المقصود ب|يقصد ب|المراد ب)\S*(\s+\S+){0,3}\s+(النظام|نظاما|الماد[هة]|النص النظامي|اللائح[هة])/ },
  { category: "تفسير نظامي", re: /(يفسر|تفسير)(\s+\S+){0,3}\s*(النظام|الماد[هة]|النص النظامي|اللائح[هة])/ },
  // (٣) اختصاص الجهة
  { category: "اختصاص جهة", re: /(تختص|يختص|ينعقد الاختصاص|الاختصاص ل|من اختصاص|صاحب[هة] الاختصاص)(\s+\S+){0,3}/, requires: GOV_BODY },
  { category: "اختصاص جهة", re: /(الجه[هة] المختص[هة] هي|المحكم[هة] المختص[هة] هي)/ },
  // (٤) الإجراء الحكومي — خطوات تقديم أو تسجيل لدى جهة
  { category: "إجراء حكومي", re: /(يقدم|تقدم|يرفع|ترفع|يسجل|تسجل)(\s+\S+){0,3}\s+(الي|لدي|امام|عبر|من خلال)\s+/, requires: GOV_BODY },
  { category: "إجراء حكومي", re: /(اجراءات|خطوات)\s+(التقديم|التسجيل|الترخيص|القيد)(\s+\S+){0,2}/, requires: GOV_BODY },
  // (٥) المدة أو المهلة
  { category: "مدة أو مهلة", re: /(مدة|مهل[هة]|ميعاد|خلال)(\s+\S+){0,2}\s+(\d+|[٠-٩]+|[يت]وما|شهرا|سنة|سنوات|ايام|ثلاثون|ثلاثين|ستون|ستين|تسعون|تسعين|مائة|اثني عشر)/ },
  { category: "مدة أو مهلة", re: /(\d+|[٠-٩]+|ثلاثين|ثلاثون|ستين|ستون|تسعين|تسعون|مائة)\s+(يوما|يوم|شهرا|شهر|سنة|سنوات|اشهر)/, requires: /(نظام|ماد[هة]|لائح[هة]|دعوي|طعن|اعتراض|تقادم|مهل[هة]|ميعاد|يمنح|يجوز|يسقط|تسقط|يشترط|يلزم|الاختصاص)/ },
  // (٦) العقوبة
  { category: "عقوبة", re: /(يعاقب|تعاقب|عقوبته|عقوبتها|بالسجن|بالحبس|غرام[هة]|يغرم)/ },
  // (٧) النسبة الرقمية
  { category: "نسبة", re: /(\d+([.,]\d+)?|[٠-٩]+([.,][٠-٩]+)?)\s*[٪%]/ },
  // (٨) الرقم الجوهري — مبلغ مالي أو عدد منسوب لسياق نظامي (غير المدة والنسبة)
  { category: "رقم جوهري", re: /(\d+|[٠-٩]+)(\s+\S+){0,1}\s*(ريال|الف ريال|ملايين|مليون ريال)/ },
  { category: "رقم جوهري", re: /(\d+|[٠-٩]+)\s+(نسخ|شهود|جلسات|درجات التقاضي)/, requires: REGULATORY_CONTEXT },
  // (٩) المتطلب النظامي
  { category: "متطلب نظامي", re: /(يشترط|تشترط|يستلزم|من شروط|يتطلب)(\s+\S+){0,2}/, requires: REGULATORY_CONTEXT },
  // (١٠) الالتزام النظامي
  { category: "التزام نظامي", re: /(يلتزم|تلتزم|يلزم|يجب)(\s+\S+){0,3}\s*(نظاما|بموجب النظام|بموجب الماد[هة]|وفق النظام|وفقا للنظام)/ },
  { category: "التزام نظامي", re: /(واجب نظامي|التزام نظامي|الزاما نظاميا)/ },
  // (١١) الاستثناء النظامي
  { category: "استثناء نظامي", re: /(يستثني|تستثني|استثناء|يستثني من ذلك|مستثنا[هة])(\s+\S+){0,3}/, requires: REGULATORY_CONTEXT },
  // (١٢) الأثر القانوني أو النظامي
  { category: "أثر قانوني أو نظامي", re: /(تسقط الدعوي|يسقط الحق|عدم القبول شكلا|يبطل|بطلان|ينقضي الحق|عديم الاثر|لا يعتد ب|يترتب(\s+\S+){0,2}(البطلان|السقوط|الانقضاء))/ },
  // (١٣) معلومة منسوبة إلى جهة حكومية
  { category: "معلومة منسوبة إلى جهة حكومية", re: /(اكدت|اكد|اوضحت|اوضح|اعلنت|اعلن|قررت|قرر|صرحت|صرح|بحسب|وفقا ل|طبقا ل)(\s+)?/, requires: GOV_BODY },
];

export function normalizeClaim(text: string): string {
  return text
    .replace(/[ً-ْـ]/g, "")
    .replace(/[إأآا]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}

// أنظمة المتن المخزّن في المنصّة — مصدرها حاضر دائماً ولها متحققها المستقل
const IN_CORPUS = /نظام المحاما[هة]|اللائح[هة] التنفيذي[هة] لنظام المحاما[هة]|قواعد السلوك المهني/;

// يرصد التفاصيل النظامية المحظورة بالمادة (١٠) في نصٍّ بلا مصدر رسمي معتمد.
// sourceCount = عدد المصادر الحكومية الرسمية للمملكة العربية السعودية المرفقة
// فعلاً (لا مجمل نتائج البحث) — بوابة السيادة المرجعية تفصلها قبل النداء.
// sourceCount > 0 ⇒ المصدر الرسمي حاضر والكاتب يكتب منه — لا رصد.
// الفحص على مستوى الجملة: الجملة المحيلة إلى متن المنصة مستثناة وحدها.
// ─── الإنفاذ بالخريطة (مبدأ الإثبات — قاعدة المحرك الواحد) ───────────────────
// «المحتوى يُبنى على الحقائق المثبتة بالمصادر»: التفصيلة النظامية في النص لا
// تُقبل لمجرد وجود مصادر — تُقبل فقط إن كانت واردة في مقطع داعم لادعاء مثبت
// في Claim–Source Mapping. ما ليس له إثبات في الخريطة يُرصد ولو امتلأ الملف
// مصادر — فالمصدر لا يغطي إلا ادعاءه.
export function article10ViolationsWithProof(text: string, provenExcerptsList: string[]): string[] {
  const normalizedProofs = provenExcerptsList.map((e) => normalizeClaim(e)).filter((e) => e.trim());
  const hits: string[] = [];
  const seen = new Set<string>();
  for (const raw of text.split(/(?<=[.؟!])\s+|\n+/)) {
    const norm = normalizeClaim(raw);
    if (!norm.trim() || IN_CORPUS.test(norm)) continue;
    for (const { category, re, requires } of CLAIM_PATTERNS) {
      const match = norm.match(re);
      if (!match) continue;
      if (requires && !requires.test(norm)) continue;
      const detail = normalizeClaim(match[0].trim());
      // التفصيلة مغطاة إن وردت داخل مقطع داعم مثبت (أو ورد المقطع في جملتها)
      const covered = normalizedProofs.some((p) => p.includes(detail) || norm.includes(p));
      if (covered) continue;
      const entry = `${category}: «${match[0].trim().slice(0, 70)}»`;
      if (seen.has(entry)) continue;
      seen.add(entry);
      hits.push(entry);
    }
  }
  return hits;
}

export function article10Violations(text: string, sourceCount: number): string[] {
  if (sourceCount > 0) return [];
  const hits: string[] = [];
  const seen = new Set<string>();
  for (const raw of text.split(/(?<=[.؟!])\s+|\n+/)) {
    const norm = normalizeClaim(raw);
    if (!norm.trim() || IN_CORPUS.test(norm)) continue;
    for (const { category, re, requires } of CLAIM_PATTERNS) {
      const match = norm.match(re);
      if (!match) continue;
      if (requires && !requires.test(norm)) continue;
      const entry = `${category}: «${match[0].trim().slice(0, 70)}»`;
      if (seen.has(entry)) continue;
      seen.add(entry);
      hits.push(entry);
    }
  }
  return hits;
}
