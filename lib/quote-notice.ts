// قرار معماري بطلب صريح من مالكة المنصة: لا تمس محرك التحليل ولا تدخل في
// احتساب أي مؤشر أو بوابة أو قرار نشر — إرشاد توعوي مع إخلاء مسؤولية المنصة.

// يرصد ما يشبه مادة مقتبسة: علامات تنصيص عربية/مزخرفة، أو نص طويل بين علامتين مستقيمتين
export function hasQuotedMaterial(text: string): boolean {
  if (!text) return false;
  if (/[«»“”]/.test(text)) return true;
  return /"[^"\n]{15,}"/.test(text) || /'[^'\n]{20,}'/.test(text);
}

