// ─────────────────────────────────────────────────────────────────────────────
// اشتقاق مستوى المخاطر من الجهات المتضررة — مصدر واحد للمنصة كلها.
//
// كان الحساب مكرراً في موضعين (review-service وreview-normalizer) بنسختين
// منفصلتين، فأي تعديل في إحداهما يترك الأخرى على حكم قديم. وُحِّد هنا.
//
// ★ الجدول بقرار مالكة المنصة — والمهنة ليست جهةً كغيرها:
//   لا جهة                → منخفض
//   المحامي وحده          → منخفض
//   الموكل وحده           → منخفض
//   المحامي + الموكل      → متوسط
//   المهنة (مع أي جهة أو وحدها) → مرتفع
//
// علّة تمييز المهنة: ضرر المحامي أو الموكل يقع على شخص بعينه ويمكن تداركه،
// أما المساس بالمهنة فأثره على المهنة كلها وعلى ثقة الناس بها — «إذا كان على
// المهنة فطبعاً دائماً لا يُسمح».
//
// «بالغ» يبقى للتهديد الشامل للمنظومة، ولا يُشتق من عدد الجهات.
// ─────────────────────────────────────────────────────────────────────────────
import type { RiskAffectedParty, RiskLevel } from "@/lib/types";

export function partiesToRiskLevel(parties: readonly RiskAffectedParty[]): RiskLevel {
  const unique = [...new Set(parties)];
  if (unique.length === 0) return "منخفض";
  if (unique.includes("المهنة")) return "مرتفع";
  if (unique.length >= 2) return "متوسط";
  return "منخفض";
}
