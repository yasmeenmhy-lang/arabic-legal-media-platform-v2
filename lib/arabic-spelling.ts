// «إن شاء الله» المرسومة صحيحةً لا تُرصد — يستثنيها هذا الفحص قبل أنماط الفصل
const CORRECT_INSHALLAH = /(?<![؀-ۿ])إن\s+شاء\s+الله(?![؀-ۿ])/;

function esc(v: string) {
  return v.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// ── ٥. توليد الصيغ المسبوقة بحرف عطف أو تعريف ──────────────────────────────
// ★ لِمَ التوليد ولا نُرخّي حدّ الكلمة؟ لأن السماح بحرفٍ عربيٍّ قبل اللفظ يفتح باب
// الإنذار الكاذب: «ان» داخل «عنوان» و«طرفان»، و«الى» داخل ما شابه. فالحدّ يبقى
// صارماً، ويُولَّد لكل لفظ نمطٌ مستقلٌّ للصيغة المسبوقة — فيبقى الرصد يقينياً.
//
// المستثنى: لفظٌ يتغيّر صواب همزته بالتعريف، وأخصّه «ان» فإن «الان» صوابها «الآن»
// لا «الأن» — فالتوليد الأعمى عليها يُنتج تصحيحاً خاطئاً، وهو أسوأ من عدم الرصد.
const NO_ARTICLE_PREFIX = new Set(["ان", "اي", "اذ", "اذا"]);

// ★ قائمة الحجب — صيغ مولَّدة ممنوع رصدها، لأحد سببين:
//   (أ) الصيغة المولَّدة كلمةٌ عربية صحيحة بذاتها: «واحد» (و+احد)، «واهم» و«فاهم»
//       (و/ف+اهم)، «فاخر» (ف+اخر)، «والى» (فعلٌ صحيح كما هو). رصدها إنذار كاذب.
//   (ب) التصحيح المولَّد خاطئ: «فانه» صوابها «فإنه» لا «فأنه»، و«الامام» تحتمل
//       «الإمام» و«الأمام». وإخراج تصحيح خاطئ أسوأ من عدم الرصد.
// الحجب لا يكلّف إلا رصداً فائتاً؛ فالتوسّع فيه مقصود.
const BLOCKED_FORMS = new Set([
  "واحد", "واهم", "فاهم", "فاخر", "والى", "فان",
  "فانه", "فانها", "فانهم", "فانك", "الامام", "فامر", "واقل", "فاقل", "فاثر",
]);

function expandPrefixes(rules: Rule[]): Rule[] {
  const out: Rule[] = [...rules];
  const add = (wrong: string, right: string, note: string) => {
    if (BLOCKED_FORMS.has(wrong)) return;
    out.push({ wrong, right, note });
  };
  for (const r of rules) {
    // الصيغ ذات التصحيح المزدوج («إن» أو «أن») لا تُولَّد — يُكتفى بها مفردة
    if (r.right.includes("»")) continue;
    for (const p of ["و", "ف"]) add(`${p}${r.wrong}`, `${p}${r.right}`, r.note);
    if (!r.wrong.startsWith("ال") && !NO_ARTICLE_PREFIX.has(r.wrong)) {
      add(`ال${r.wrong}`, `ال${r.right}`, r.note);
      add(`وال${r.wrong}`, `وال${r.right}`, r.note);
    }
  }
  return out;
}

// صيغ مسبوقة تُكتب صريحةً لأن تصحيحها لا يُشتق آلياً من الصيغة المفردة
const EXPLICIT_PREFIXED: Rule[] = [
  { wrong: "وان", right: "وأن", note: "همزة قطع" },
  { wrong: "فانه", right: "فإنه", note: "همزة قطع" },
  { wrong: "فانها", right: "فإنها", note: "همزة قطع" },
  { wrong: "فانهم", right: "فإنهم", note: "همزة قطع" },
];

// كل قواعد الكلمة المفردة مجموعةً — الترتيب لا يؤثر (التطابق بحدود الكلمة)
const WORD_RULES: Rule[] = [
  ...expandPrefixes([
    ...HAMZA_RULES,
    ...LETTER_RULES,
    ...TAA_WORDS.map(([wrong, right]) => ({ wrong, right, note: "تاء مربوطة" })),
  ]),
  ...EXPLICIT_PREFIXED,
];

/**
 * رصد إملائي حتمي — النتيجة نفسها لكل نصّ في كل مرة.
 * الحدود: لا يُطابَق اللفظ إلا مستقلاً — لا داخل كلمة أطول ولا ملتصقاً بحرف عربي،
 * فلا تُرصد «الى» داخل «الىٰ» ولا «ان» داخل «انسان».
 */
export function detectArabicSpelling(text: string): SpellingHit[] {
  const hits: SpellingHit[] = [];
  const seen = new Set<string>();

  const push = (excerpt: string, right: string, note: string, start: number) => {
    const key = `${start}:${excerpt}`;
    if (seen.has(key)) return;
    seen.add(key);
    hits.push({
      excerpt,
      message: note ? `«${excerpt}» — ${note}؛ الصواب: «${right}».` : `«${excerpt}» — الصواب: «${right}».`,
      suggestion: `استبدل «${excerpt}» بـ «${right}».`,
      start,
      end: start + excerpt.length,
    });
  };

  // أنماط الفصل أولاً — كي تُرصد العبارة كاملة قبل أن يُرصد جزؤها كلمةً مفردة
  const phraseSpans: Array<[number, number]> = [];
  for (const rule of PHRASE_RULES) {
    const re = new RegExp(rule.re.source, "g");
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
      // العبارة المرسومة صحيحةً «إن شاء الله» لا تُعدّ خطأً
      if (CORRECT_INSHALLAH.test(m[0]) && rule.right === "إن شاء الله") continue;
      phraseSpans.push([m.index, m.index + m[0].length]);
      push(rule.excerptOf(m[0]), rule.right, rule.note, m.index);
    }
  }
  const insidePhrase = (i: number) => phraseSpans.some(([a, b]) => i >= a && i < b);

  for (const rule of WORD_RULES) {
    const re = new RegExp(`(?<![\\u0600-\\u06FF])${esc(rule.wrong)}(?![\\u0600-\\u06FF])`, "g");
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
      if (insidePhrase(m.index)) continue; // جزء من عبارة رُصدت كاملة
      push(m[0], rule.right, rule.note, m.index);
    }
  }

  return hits.sort((a, b) => a.start - b.start);
}
