// الطبقة الإملائية الثابتة (بقرار مالكة المنصة: «التدقيق كان يلتقط وحالياً لا»)
//
// محرّك اللغة يعمل بالذكاء وحده، ونموذجه لا يقبل حرارة صفر — فالنتيجة تختلف
// بين تشغيل وآخر على النص نفسه: كلمة تُرصد مرة وتفوت مرة، وتُصنَّف إملاءً مرة
// ونحواً مرة. وقياسٌ لا يثبت على حكم واحد لا يُبنى عليه.
//
// هذه الطبقة حتمية بالكامل: لا ذكاء، ولا شبكة، ولا تكلفة — ما تلتقطه مرة
// تلتقطه كل مرة بالنتيجة نفسها. تعمل قبل الذكاء وتُدمج نتائجها معه، فتضمن
// أرضية ثابتة لا تنزل عنها المنصة أبداً وإن تقلّب النموذج.
//
// ★ قاعدة الإدراج الصارمة — صفر إنذار كاذب:
//   لا تُدرَج صيغة في هذا الملف إلا إذا كانت **خاطئة في كل موضع بلا استثناء**.
//   أي لفظ له وجه صحيح في أي سياق (مثل «علي» اسماً، و«فيه» و«عليه» و«لديه»
//   وكل ما آخره «يه» ضميراً) ممنوع إدراجه. ولهذا لا توجد هنا قاعدة عامة
//   للتاء المربوطة ولا للهمزة: القواعد العامة تُخطئ في المضاف إليه والضمائر،
//   فالمعتمد قائمةٌ مُنتقاة لفظاً لفظاً — يقينُ الرصد مقدَّمٌ على سعته.
// ═══════════════════════════════════════════════════════════════════════════

